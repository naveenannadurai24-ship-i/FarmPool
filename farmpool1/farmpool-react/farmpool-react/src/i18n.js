export function initialLang() {
  try {
    const saved = localStorage.getItem("hp_lang");
    if (saved === "en" || saved === "ta") return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || "").toLowerCase().startsWith("ta") ? "ta" : "en";
}

export function translate(lang, key, params) {
  let text = I18N[lang]?.[key];
  if (text === undefined) text = I18N.en[key];
  if (text === undefined) text = key;
  if (params) text = text.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return text;
}
